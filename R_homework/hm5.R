print(motifs2_upper)
# 
profile <- apply(motifs2_upper, 2, function(x) {
  counts <- table(factor(x, levels = c("A", "C", "G", "T")))
  counts / sum(counts)
})

# scoreMotifs
scoreMotifs <- function(motifs) {
  motifs <- matrix(toupper(motifs), nrow = nrow(motifs))
  sum(apply(motifs, 2, function(col) length(col) - max(table(col))))
}

# Вычисляем score для motifs2
motifs2_score <- scoreMotifs(motifs2)

# Выводим результат
cat("Score для motifs2:", motifs2_score, "\n")

# Получаем консенсусную последовательность
consensus <- apply(profile, 2, function(col) {
  nucleotides <- c("A", "C", "G", "T")
  nucleotides[which.max(col)]
})
consensus_string <- paste(consensus, collapse = "")

# Выводим результат
cat("Консенсусная последовательность:\n")
cat(consensus_string, "\n")

